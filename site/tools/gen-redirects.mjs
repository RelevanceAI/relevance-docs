/**
 * Emits redirect rules from docs.json.
 *
 * 93 rules, of which 14 are WILDCARDS (`/chat/:slug*`) covering whole
 * subtrees from the pre-reorg IA. Next's static export cannot serve
 * redirects at all -- `output: 'export'` drops next.config `redirects()` --
 * so every rule has to land in host config. Both Cloudflare and Vercel
 * handle wildcards, so this emits both.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const docs = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs.json'), 'utf8'));
const all = docs.redirects ?? [];
const isWild = (r) => /[*:]/.test(r.source) || /[*:]/.test(r.destination);
const withBase = (p) => `/docs${p}`.replace(/\/+/g, '/');

const exact = all.filter((r) => !isWild(r));
const wild = all.filter(isWild);

// Cloudflare: `*` matches, `:splat` substitutes. Mintlify's `:slug*` is the same idea.
const cf = (r) => {
  const from = withBase(r.source).replace(/:\w+\*/g, '*');
  const to = withBase(r.destination).replace(/:\w+\*/g, ':splat').replace(/(?<!:)\*/g, ':splat');
  return `${from}  ${to}  301`;
};

// Exact rules first: Cloudflare matches top-down and a wildcard would shadow them.
const body = [
  '# Generated by site/tools/gen-redirects.mjs from docs.json. Do not edit.',
  ...exact.map(cf),
  '',
  '# Wildcard subtree redirects from the pre-reorg IA',
  ...wild.map(cf),
  '',
].join('\n');
fs.writeFileSync(path.join(ROOT, 'site/public/_redirects'), body);

const vercel = {
  redirects: all.map((r) => ({
    source: withBase(r.source),
    destination: withBase(r.destination),
    permanent: true,
  })),
};
fs.writeFileSync(path.join(ROOT, 'site/vercel.json'), JSON.stringify(vercel, null, 2) + '\n');

console.log(`redirects: ${all.length} (${exact.length} exact, ${wild.length} wildcard)`);
console.log('wrote site/public/_redirects and site/vercel.json');
