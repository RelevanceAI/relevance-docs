/**
 * Emits redirect rules from docs.json.
 *
 * 93 rules, of which 14 are WILDCARDS (`/chat/:slug*`) covering whole
 * subtrees from the pre-reorg IA. Next's static export cannot serve
 * redirects at all -- `output: 'export'` drops next.config `redirects()` --
 * so every rule has to land in host config. Both Cloudflare and Vercel
 * handle wildcards, so this emits both.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const docs = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs.json'), 'utf8'));
const all = docs.redirects ?? [];
const isWild = (r) => /[*:]/.test(r.source) || /[*:]/.test(r.destination);
const withBase = (p) => `/docs${p}`.replace(/\/+/g, '/');

const exact = all.filter((r) => !isWild(r));
const wild = all.filter(isWild);

/**
 * Vercel uses path-to-regexp, which requires NAMED wildcards (`:path*`).
 * Mintlify's docs.json mixes two forms -- `:slug*` (already valid) and a bare
 * `*` (not valid). Passing the bare form straight through made Vercel reject
 * the ENTIRE deployment at creation time with "invalid `source` pattern",
 * before any build ran. Three rules were affected and they took the other 160
 * down with them.
 */
const toVercelPattern = (p) => p.replace(/(?<!:[\w]{0,32})\*/g, ':path*').replace(/:(\w+)\*/g, ':$1*');
const vercelRule = (r) => {
  // A bare `*` becomes `:path*` on BOTH sides so the param names line up.
  const hasBare = /(?<!\w)\*/.test(r.source.replace(/:\w+\*/g, ''));
  const conv = (p) => (hasBare ? p.replace(/(?<!\w)\*/g, ':path*') : p);
  return { source: withBase(conv(r.source)), destination: withBase(conv(r.destination)) };
};

// Cloudflare: `*` matches, `:splat` substitutes. Mintlify's `:slug*` is the same idea.
const cf = (r) => {
  const from = withBase(r.source).replace(/:\w+\*/g, '*');
  const to = withBase(r.destination).replace(/:\w+\*/g, ':splat').replace(/(?<!:)\*/g, ':splat');
  return `${from}  ${to}  301`;
};

/**
 * Folder paths without a page of their own.
 *
 * Mintlify 307s /docs/build/knowledge to the folder's first child. Fumadocs
 * has no page there at all, so those links 404. Every content directory that
 * has a meta.json but no index.mdx gets a redirect to its first real page,
 * in the order meta.json lists them.
 */
const DOCS_DIR = path.join(ROOT, 'site/content/docs');
const folderRules = [];

// Falls back to the first .mdx in the tree when a directory has no
// meta.json -- gen-nav only writes one where docs.json puts a group, so
// folders like build/agents/build-your-agent have none.
const firstMdx = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p2 = path.join(dir, e.name);
    if (e.isFile() && e.name.endsWith('.mdx')) {
      return path.posix.join(path.relative(DOCS_DIR, dir), e.name.replace(/\.mdx$/, ''));
    }
    if (e.isDirectory()) {
      const nested = firstMdx(p2);
      if (nested) return nested;
    }
  }
  return null;
};

const firstPage = (dir) => {
  const metaPath = path.join(dir, 'meta.json');
  if (!fs.existsSync(metaPath)) return firstMdx(dir);
  const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
  for (const entry of meta.pages ?? []) {
    if (entry.startsWith('---')) continue;
    const asFile = path.join(dir, `${entry}.mdx`);
    if (fs.existsSync(asFile)) return path.posix.join(path.relative(DOCS_DIR, dir), entry);
    const asIndex = path.join(dir, entry, 'index.mdx');
    if (fs.existsSync(asIndex)) return path.posix.join(path.relative(DOCS_DIR, dir), entry);
    const nested = firstPage(path.join(dir, entry));
    if (nested) return nested;
  }
  return firstMdx(dir);
};

(function walkDirs(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const sub = path.join(dir, e.name);
    walkDirs(sub);
    const rel = path.relative(DOCS_DIR, sub).split(path.sep).join('/');
    const hasOwnPage = fs.existsSync(path.join(sub, 'index.mdx')) ||
                       fs.existsSync(path.join(DOCS_DIR, `${rel}.mdx`));
    if (hasOwnPage) continue;
    const target = firstPage(sub);
    if (target) folderRules.push({ source: `/${rel}`, destination: `/${target}` });
  }
})(DOCS_DIR);

// Exact rules first: Cloudflare matches top-down and a wildcard would shadow them.
const body = [
  '# Generated by site/tools/gen-redirects.mjs from docs.json. Do not edit.',
  '',
  '# /docs itself 308s to the introduction page on Mintlify today.',
  '/docs  /docs/get-started/introduction  308',
  '',
  ...exact.map(cf),
  '',
  '# Folder paths with no page of their own (Mintlify 307s these)',
  ...folderRules.map((r) => `${withBase(r.source)}  ${withBase(r.destination)}  307`),
  '',
  '# Wildcard subtree redirects from the pre-reorg IA',
  ...wild.map(cf),
  '',
].join('\n');
fs.writeFileSync(path.join(ROOT, 'site/public/_redirects'), body);

/**
 * Complete Vercel project config, not just redirects.
 *
 * Vercel reads this from the project's Root Directory, which must be set to
 * `site`. Framework detection is disabled on purpose: this is a static
 * export packed by tools/pack-dist.mjs, not a Next.js app for Vercel to
 * build and serve itself.
 */
/**
 * The /docs entry point. Mintlify 308s /docs to the introduction page.
 * This was originally added to the Cloudflare _redirects body only, so on
 * Vercel /docs itself 404'd -- the same one-host-not-the-other mistake as
 * the bare wildcards. It belongs in both configs.
 */
const ENTRY_RULE = { source: '/docs', destination: '/docs/get-started/introduction' };

const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  framework: null,
  /**
   * Vercel defaults cleanUrls to FALSE, so a plain static output is served
   * ONLY at .html paths: /docs/get-started/introduction 404s while
   * /docs/get-started/introduction.html renders. Cloudflare Pages does this
   * implicitly, which is why it went unnoticed.
   *
   * With it on, `about.html` is served at `/about` and `/about.html` 308s to
   * `/about` -- so the .html forms cannot be indexed as duplicates of the
   * canonical clean URLs.
   */
  cleanUrls: true,
  // `npm run build`, not a bare `next build`: npm puts node_modules/.bin on
  // PATH, a plain shell does not. A bare `next` fails with
  // "next: command not found" wherever the runner has not already added it.
  buildCommand: 'npm run build && node tools/pack-dist.mjs',
  outputDirectory: 'dist',
  trailingSlash: false,
  redirects: [
    { ...ENTRY_RULE, permanent: false },
    ...[...all, ...folderRules].map((r) => ({
      ...vercelRule(r),
      permanent: !/[*:]/.test(r.source) && !folderRules.includes(r),
    })),
  ],
  headers: [
    {
      // Hashed build assets never change under a given name.
      source: '/docs/_next/static/(.*)',
      headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }],
    },
    {
      source: '/docs/(images|videos)/(.*)',
      headers: [{ key: 'Cache-Control', value: 'public, max-age=86400, stale-while-revalidate=604800' }],
    },
  ],
};
fs.writeFileSync(path.join(ROOT, 'site/vercel.json'), JSON.stringify(vercel, null, 2) + '\n');

// Cloudflare Pages equivalent of the cache headers above.
fs.writeFileSync(path.join(ROOT, 'site/public/_headers'),
  [
    '# Generated by site/tools/gen-redirects.mjs. Do not edit.',
    '/docs/_next/static/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '/docs/images/*',
    '  Cache-Control: public, max-age=86400, stale-while-revalidate=604800',
    '/docs/videos/*',
    '  Cache-Control: public, max-age=86400, stale-while-revalidate=604800',
    '',
  ].join('\n'));

console.log(`redirects: ${all.length} from docs.json (${exact.length} exact, ${wild.length} wildcard)`);
console.log(`           + ${folderRules.length} folder-index redirects`);
console.log('wrote site/public/_redirects, site/public/_headers and site/vercel.json');
